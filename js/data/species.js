const bySci = new Map(SPECIES.map(s => [s.sci.toLowerCase(), s]));
const byId = new Map(SPECIES.map(s => [String(s.id), s]));
const byInat = new Map(SPECIES.filter(s => s.inat).map(s => [Number(s.inat), s]));
const byGbif = new Map(SPECIES.filter(s => s.gbif).map(s => [Number(s.gbif), s]));

/** Find a curated card by scientific name or provider id. */
export function findSpecies({ sci, id, inat, gbif } = {}) {
  return (
    (id != null && byId.get(String(id))) ||
    (inat != null && byInat.get(Number(inat))) ||
    (gbif != null && byGbif.get(Number(gbif))) ||
    (sci && bySci.get(String(sci).toLowerCase())) ||
    null
  );
}
